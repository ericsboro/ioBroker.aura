/** Fast lookup by type */
export const WIDGET_BY_TYPE = Object.fromEntries(WIDGET_REGISTRY.map((m) => [m.type, m])) as Record<
    WidgetType,
    WidgetMeta
>;

export function conditionSlotsFor(type: WidgetType): ConditionSlot[] {
    return WIDGET_BY_TYPE[type]?.conditionSlots ?? DEFAULT_CONDITION_SLOTS;
}

/** All {{key}} placeholder names available in popup views (union of all popupDefaults keys + dp/parent/name).
 *  `dp` is the trigger's main datapoint, `parent` its parent strang (id without the last segment),
 *  `name` its last segment — so {{parent}}.Trigger resolves to a sibling of the main DP. */
export const ALL_POPUP_PLACEHOLDER_KEYS: string[] = (() => {
    const keys = new Set<string>(['dp', 'parent', 'name']);
    WIDGET_REGISTRY.forEach((m) => Object.keys(m.popupDefaults ?? {}).forEach((k) => keys.add(k)));
    return [...keys].sort();
})();

/**
 * Returns the effective default size for a widget type.
 * Checks user overrides first, falls back to registry defaults.
 */
export function getEffectiveSize(
    type: string,
    overrides: Record<string, { w: number; h: number }>,
): { w: number; h: number } {
    if (overrides[type]) return overrides[type];
    const meta = WIDGET_BY_TYPE[type as WidgetType];
    return meta ? { w: meta.defaultW, h: meta.defaultH } : { w: 2, h: 2 };
}
